import esbuild from 'esbuild'
import esbuildSvelte from 'esbuild-svelte'
import { copyFile, mkdir } from 'node:fs/promises'
import { builtinModules } from 'node:module'
import path from 'path'
import process from 'process'
import { sveltePreprocess } from 'svelte-preprocess'

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`

const prod = process.argv[2] === 'production'
const vaultPluginDir = String.raw`D:\ObsidianNotes\G'sV\.obsidian\plugins\keronmisearch`

const copyPluginAssets = {
  name: 'copy-plugin-assets',
  setup(build) {
    build.onEnd(async () => {
      await mkdir(vaultPluginDir, { recursive: true })
      await Promise.all([
        copyFile('manifest.json', path.join(vaultPluginDir, 'manifest.json')),
        copyFile(
          path.join('assets', 'styles.css'),
          path.join(vaultPluginDir, 'styles.css')
        ),
      ])
    })
  },
}

const context = await esbuild.context({
  banner: {
    js: banner,
  },
  entryPoints: ['./src/main.ts'],
  bundle: true,
  external: [
    'obsidian',
    'electron',
    '@codemirror/autocomplete',
    '@codemirror/collab',
    '@codemirror/commands',
    '@codemirror/language',
    '@codemirror/lint',
    '@codemirror/search',
    '@codemirror/state',
    '@codemirror/view',
    '@lezer/common',
    '@lezer/highlight',
    '@lezer/lr',
    ...builtinModules,
  ],
  outfile: path.join(vaultPluginDir, 'main.js'),
  plugins: [
    esbuildSvelte({
      compilerOptions: { css: 'injected' },
      preprocess: sveltePreprocess(),
    }),
    copyPluginAssets,
  ],
  format: 'cjs',
  target: 'chrome98',
  logLevel: 'info',
  sourcemap: prod ? false : 'inline',
  treeShaking: true,
  minify: prod,
})

if (prod) {
  await context.rebuild()
  process.exit(0)
} else {
  await context.watch()
}
